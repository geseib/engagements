/**
 * WHAT THE ROOM SAID, AND WHAT WORKIE SAID BACK, NEVER REACH THE LOGS.
 *
 * ── THE LEAK ───────────────────────────────────────────────────────────────
 *
 * `lambda-functions/game/get-ai-summary.js` decrypts a round's ANSWER rows —
 * `decryptItems(summaryOrgId, 'answer', …)`; `Answer` is on
 * ENCRYPTED_FIELDS.answer and websocket/message.js stores it as an envelope —
 * because the prompt has to be built from the room's own words. It then wrote
 * those words to CloudWatch, in the clear, a dozen different ways:
 *
 *   - `🔍 CORRECTNESS CHECK: Player "…" answered "…"`, one line per answer
 *   - `🔍 DEBUG: AI Summary - answers structure:` (a whole decrypted row), the
 *     voteTallies dump (each tally carries `answerText`) and one
 *     `answer="…"` line per participant
 *   - the trivia and wavelength template-variable dumps: `triviaResponses`,
 *     `playerResponses`, `responsesText`, `wavelengthWords`, `commonWords`
 *   - `🤖 FULL AI PROMPT CONSTRUCTED:` — the entire prompt, which embeds every
 *     answer verbatim, the question, and the host's own brief
 *   - `📝 AI Response preview:` and `🔍 PARSING: First 300 chars:` — the start
 *     of Workie's reply, which is written from the answers (and stored as
 *     ENCRYPTED_FIELDS.aiSummary)
 *
 * and the question itself, which an organisation's set holds as ciphertext
 * (ENCRYPTED_FIELDS.question: Title, Detail, optionA..F, AnswerDetails), was
 * decrypted and then dumped field by field — including `correctAnswer`, which
 * many sets spell as the right option's TEXT. game/get-results.js (closing a
 * trivia round) and game/create-report.js (the trivia debug block) printed the
 * title and the right answer the same way.
 *
 * Encrypting a field and then logging it is not encrypting it: anyone who can
 * read the log group reads the room, with no key and no audit trail.
 *
 * ── THE RULE ───────────────────────────────────────────────────────────────
 *
 * A log line says WHAT HAPPENED — game, question number, player name, counts,
 * an answer's LENGTH or type, isCorrect, points, whether the AI call succeeded
 * and how long its reply was. Never what was said, asked or written back.
 * (The same rule tests/answer-content-not-logged.js holds message.js to.)
 *
 * rejects: an answer, a question field that is encrypted at rest, the session
 *          brief, or any part of the AI's reply, in any console.log / info /
 *          warn / error / debug output while get-ai-summary.js generates or
 *          serves a text, trivia or wavelength round's summary — or while
 *          get-results.js closes the round, or create-report.js reports it;
 *          a fix that stops the answers reaching the MODEL (the prompt must
 *          still carry them); a fix that stops the summary being produced,
 *          stored encrypted, or served; a fix that silences the lines (they
 *          must still say what happened).
 *
 * FIXTURES ARE PRODUCED, NOT WRITTEN: every ANSWER row here is what the real
 * websocket/message.js stores, encrypted by the real encryptItem; trivia and
 * wavelength rounds are closed by the real get-results.js; the summary is
 * generated by the real worker path of get-ai-summary.js and read back through
 * its real HTTP route. Only the AWS clients are fakes — Bedrock answers with
 * text carrying its own marker, so its reply can be looked for too.
 */
