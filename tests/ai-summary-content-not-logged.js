/**
 * Generate the round's summary and read it back, capturing every console line
 * of both. Asserts the summary is still built from the answers, stored sealed
 * and served — then that nothing the room said, asked or was told back is in
 * the logs, and that the logs still say what happened.
 */
async function summariseAndCheck(gameId, secrets, { answerMarkers, facts }) {
  const generated = await captureLogs(() => generateSummary(gameId));
  const read = await captureLogs(() => readSummary(gameId));
  const logs = `${generated.logs}\n${read.logs}`;
  const call = bedrockCalls[bedrockCalls.length - 1];

  await check('the summary worker completes', () =>
    assert.deepStrictEqual(generated.out && generated.out.ok, true, JSON.stringify(generated.out)));
  await check('the model is still sent what the room said', () => {
    assert.strictEqual(bedrockCalls.length, 1, `Bedrock was called ${bedrockCalls.length} time(s)`);
    for (const needle of answerMarkers) {
      assert.ok(call.prompt.toLowerCase().includes(needle.toLowerCase()), `the prompt lacks ${needle}`);
    }
  });
  await check('the summary is stored, encrypted at rest', () => {
    const row = summaryRow(gameId);
    assert.ok(row, 'no AISummary row was written');
    assert.ok(isEnvelope(row.SummaryText), `SummaryText is stored as ${JSON.stringify(row.SummaryText)}`);
    assert.ok(isEnvelope(row.MarkdownResponse), 'MarkdownResponse is stored in the clear');
  });
  await check('…and served, in the clear, to the room', () => {
    assert.strictEqual(read.out.statusCode, 200, `answered ${read.out.statusCode}: ${read.out.body}`);
    const body = JSON.parse(read.out.body);
    assert.strictEqual(body.fromCache, true);
    assert.ok(String(body.markdownResponse).includes(call.said), 'the served summary is not the model\'s reply');
  });
  await check('nothing said, asked or written back is in any log line', () =>
    assertNothingLogged(logs, { ...secrets, "Workie's reply": call.said }));
  await check('…and the logs still say what happened', () => {
    for (const fact of [gameId, ...facts]) {
      const ok = fact instanceof RegExp ? fact.test(logs) : logs.includes(fact);
      assert.ok(ok, `no log line mentions ${fact}:\n${logs.slice(0, 4000)}`);
    }
  });
  return logs;
}

