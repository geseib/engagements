/**
 * One live room on ASK#001, owned by an organisation, playing a question from
 * that organisation's own set — so the session brief, the question and every
 * ANSWER row are ciphertext at rest. Returns the markers seeded into it.
 */
async function seedRoom({ gameId, gameType }) {
  table.store.clear(); sent.length = 0; frames.length = 0; bedrockCalls.length = 0;
  kmsStubs.forgetAllOrgs();
  const PK = `GAME#${gameId}`;
  const secrets = {
    'the session title': marker('title'),
    "the host's AI instructions": marker('ctx'),
    'the event details': marker('details'),
    'the question title': marker('q'),
    'the question detail': marker('detail'),
    'the reveal (AnswerDetails)': marker('reveal'),
  };

  put(await C.encryptItem(ORG, 'session', {
    PK, SK: 'METADATA', GameType: gameType, Started: true, orgId: ORG,
    Title: `Retro ${secrets['the session title']}`,
    AIContext: `Lead with ${secrets["the host's AI instructions"]}`,
    Details: `Offsite ${secrets['the event details']}`,
    QuestionSetId: SET_ID, QuestionSetScope: 'org', QuestionSetVersion: 1,
    HostPreferences: { anonymousUntilReveal: false },
  }));
  put({ PK, SK: 'STATE', State: 'ASK#001', LessonNumber: 1, CurrentQuestionId: '001' });
  put({ PK, SK: `CONNECTION#${HOST}`, ConnectionId: HOST, ConnectionType: 'HOST', GameId: gameId });
  for (const name of PLAYERS) {
    const id = `phone-${name}`;
    put({ PK, SK: `CONNECTION#${id}`, ConnectionId: id, ConnectionType: 'PLAYER', GameId: gameId, PlayerName: name });
  }
  // Authors revealed, so nothing below is hidden for anonymity's sake — the
  // names may travel; only what was said may not.
  put({ PK, SK: 'ROUND#001', QuestionNumber: '001', AuthorsRevealed: true });

  // The REF row as next-question.js writes it, and the question where that
  // pinned pair addresses it — an org set, so its content is encrypted.
  put({
    PK, SK: 'QUESTION#001#REF', SourceQuestionId: 'QUESTION#c001#001',
    SetId: SET_ID, SetVersion: 1, SetScope: 'org', SetOrgId: ORG,
    StartedAt: new Date().toISOString(),
  });
  put({ PK: `ORG#${ORG}#SETS`, SK: `SET#${SET_ID}`, activeVersion: 1, versions: [{ version: 1 }] });
  const question = {
    PK: `ORG#${ORG}#SET#${SET_ID}#v1`, SK: 'QUESTION#c001#001', Category: 'c001',
    Title: `Largest planet ${secrets['the question title']}`,
    Detail: `By mass ${secrets['the question detail']}`,
    AnswerDetails: `Because ${secrets['the reveal (AnswerDetails)']}`,
    points: 10,
  };
  if (gameType === 'trivia') {
    secrets["the right option's text"] = marker('opt');
    secrets['a wrong option'] = marker('wrong');
    const right = `Jupiter ${secrets["the right option's text"]}`;
    // The right answer spelled as the option's TEXT — the shape that sent the
    // right answer to the logs in the clear on every `correctAnswer` dump.
    Object.assign(question, {
      optionA: `Mercury ${secrets['a wrong option']}`, optionB: right,
      optionC: 'Neptune', optionD: 'Saturn', correctAnswer: right,
    });
  }
  put(await C.encryptItem(ORG, 'question', question));

  // Workie's house prompts, where findDefaultPromptId's fallback looks.
  for (const id of ['lessons-learned', 'trivia-basic']) {
    const s3Key = `prompts/${id}.json`;
    put({ PK: 'AIPROMPTS', SK: `AIPROMPT#${id}`, promptId: id, name: id, s3Key });
    promptBodies.set(s3Key, { id, name: id, template: TEMPLATE });
  }
  return secrets;
}

