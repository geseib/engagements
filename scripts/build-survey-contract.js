#!/usr/bin/env node
/**
 * THE SURVEY CONTRACT, AS THE BROWSER'S AUTHORING PROMPTS NEED IT.
 *
 *   node scripts/build-survey-contract.js           # write src/src/config/surveyContract.json
 *   node scripts/build-survey-contract.js --check   # exit 1 if the committed file is stale
 *
 * The poll and survey "Copy AI authoring prompt" text (src/src/config/
 * aiAuthoringPrompt.js) tells somebody else's AI which columns each question
 * kind uses, what values they take and what the limits are. Those facts live
 * in lambda-functions/admin/shared/survey-kinds.js — the module the importer
 * validates every row with — and the frontend cannot import outside src/. So
 * this writes them into a JSON file the prompt reads, the pattern
 * scripts/build-repo-prompts.js set for repoPrompts.json. The output is
 * committed; tests/survey-contract-fresh.js fails when it is stale.
 *
 * NOTHING IS RETYPED. The kinds, columns, header and vocabularies are the
 * module's exports. The two things it does not export — which columns a kind
 * uses, and the numeric limits — are MEASURED by asking the module: a row with
 * every column filled is read as each kind and `itemFields` says what was kept;
 * `validateSurvey` is probed with growing option lists and answer limits until
 * it stops objecting. A limit changed in survey-kinds.js therefore changes the
 * prompt on the next build, and the freshness test makes sure that build runs.
 */
const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..');
const OUT = path.join(REPO, 'src', 'src', 'config', 'surveyContract.json');
const K = require(path.join(REPO, 'lambda-functions', 'admin', 'shared', 'survey-kinds.js'));

/** A cell for every column, each a value its kind accepts, so nothing is dropped for being blank. */
const EVERY_COLUMN = {
  Required: 'true', Options: 'a|b|c|d', AllowMultiple: 'true', MaxPicks: '2', AllowOther: 'true',
  Shuffle: 'true', Scale: '1-5', LowLabel: 'low', HighLabel: 'high', YesLabel: 'yes', NoLabel: 'no',
  Unsure: 'true', FollowUpWhen: 'no', FollowUpPrompt: 'why?', RankTop: '2', TextLength: 'short',
  MaxLength: '280', Placeholder: 'hint', Themes: 'true',
};

/** The columns a kind keeps, in the contract's order (Kind first). */
function columnsFor(kind) {
  const fields = K.surveyFieldsFromCells((column) => (column === 'Kind' ? kind : EVERY_COLUMN[column] ?? ''));
  const kept = new Set(Object.keys(K.itemFields(fields)));
  return K.SURVEY_CSV_COLUMNS.filter((column) => kept.has(column[0].toLowerCase() + column.slice(1)));
}

/** The smallest and largest option count `validateSurvey` accepts for a list kind. */
function optionRange(kind) {
  const ok = [];
  for (let n = 0; n <= 30; n += 1) {
    const options = Array.from({ length: n }, (_, i) => `option ${i + 1}`);
    const fields = K.surveyFieldsFromCells((column) => ({ Kind: kind, Options: options.join('|') })[column] ?? '');
    if (K.validateSurvey(fields).length === 0) ok.push(n);
  }
  return { min: Math.min(...ok), max: Math.max(...ok) };
}

/** The answer-limit range for an open question. */
function maxLengthRange() {
  const ok = [];
  for (let n = 1; n <= 5000; n += 1) {
    const fields = K.surveyFieldsFromCells((column) => ({ Kind: 'text', MaxLength: String(n) })[column] ?? '');
    if (K.validateSurvey(fields).length === 0) ok.push(n);
  }
  return { min: Math.min(...ok), max: Math.max(...ok) };
}

/** What a blank MaxLength becomes, per length. */
function defaultMaxLength() {
  const out = {};
  for (const length of K.TEXT_LENGTHS) {
    out[length] = K.surveyFieldsFromCells((column) => ({ Kind: 'text', TextLength: length })[column] ?? '').maxLength;
  }
  return out;
}

function build() {
  const columnsByKind = Object.fromEntries(K.KINDS.map((kind) => [kind, columnsFor(kind)]));
  return {
    $comment: 'GENERATED by scripts/build-survey-contract.js from lambda-functions/admin/shared/survey-kinds.js. Do not edit; run the script. tests/survey-contract-fresh.js fails when this is stale.',
    kinds: [...K.KINDS],
    pollKinds: [...K.POLL_KINDS],
    surveyCategory: K.SURVEY_CATEGORY,
    header: `${K.SURVEY_CSV_HEADER},Tags`,
    kindColumns: [...K.SURVEY_CSV_COLUMNS],
    columnsByKind,
    scales: [...K.SCALES],
    followUps: [...K.FOLLOW_UPS],
    textLengths: [...K.TEXT_LENGTHS],
    defaultMaxLength: defaultMaxLength(),
    limits: {
      choiceOptions: optionRange('choice'),
      rankItems: optionRange('rank'),
      maxLength: maxLengthRange(),
    },
  };
}

const render = () => `${JSON.stringify(build(), null, 2)}\n`;

if (require.main === module) {
  const next = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== next) {
      process.stderr.write(`${path.relative(REPO, OUT)} is stale. Run: node scripts/build-survey-contract.js\n`);
      process.exit(1);
    }
    process.stdout.write(`${path.relative(REPO, OUT)} is current.\n`);
  } else {
    fs.writeFileSync(OUT, next);
    process.stdout.write(`wrote ${path.relative(REPO, OUT)}\n`);
  }
}

module.exports = { build, render, OUT };
