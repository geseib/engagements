#!/usr/bin/env node
/**
 * progress.js — roll the unit records into docs/design/themes/PROGRESS.md.
 *
 * Each worker writes ONLY its own docs/design/themes/records/<unit>.md (front matter between
 * --- lines; records/TEMPLATE.md). No shared file is ever appended to, so parallel units never
 * collide; the coordinator runs this on the integration branch after each merge and commits
 * the regenerated PROGRESS.md. The totals come from measure.js, never from a record.
 */
const fs = require('fs');
const path = require('path');
const C = require('./lib/common');
const M = require('./lib/manifest');
const { treeReader, measureAll } = require('./measure');

const DIR = path.join(C.REPO, 'docs', 'design', 'themes');
const HELP = `usage: node scripts/skins/progress.js [--write] [--records <dir>]

  (default)   print PROGRESS.md to stdout
  --write     write docs/design/themes/PROGRESS.md
  --selftest  parse the fixture records; a record missing its unit field must be reported
  --selftest --plant   the fixture's good record loses its status: must fail
  --help`;

function parse(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (kv) out[kv[1]] = kv[2].trim();
  }
  return out;
}

function readRecords(dir) {
  const recs = []; const bad = [];
  if (!fs.existsSync(dir)) return { recs, bad };
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.md') && !/^(TEMPLATE|EXAMPLE)/.test(x)).sort()) {
    const r = parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    if (!r || !r.unit || !r.status) { bad.push(`${f}: no front matter with unit and status`); continue; }
    recs.push({ file: f, ...r });
  }
  return { recs, bad };
}

function render(recs, bad) {
  const units = M.load();
  const byUnit = {};
  for (const r of recs) byUnit[r.unit] = r;
  const all = measureAll(treeReader({}));
  const rows = Object.values(all);
  const sum = (k) => rows.reduce((a, r) => a + (r[k] || 0), 0);
  const lines = [
    '# Site skins: progress',
    '',
    `Generated by \`node scripts/skins/progress.js --write\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand:`,
    'each unit writes its own `records/<unit>.md`; totals are re-measured, never copied.',
    '',
    '## Totals now (measure.js)',
    '',
    '| Colour literals in rules | in token decls | named white/black | font-family | font: shorthand | var(--primary…) | var(--secondary) |',
    '|---:|---:|---:|---:|---:|---:|---:|',
    `| ${sum('ruleLiterals')} | ${sum('declLiterals')} | ${sum('namedLiterals')} | ${sum('fontLiterals')} | ${sum('fontShorthand')} | ${sum('primary')} | ${sum('secondary')} |`,
    '',
    'At the start (16e8c3dd, INVENTORY.md): 1,731 · 514 · 177 · 40 · 3 · 796 · 153.',
    '',
    '## Units',
    '',
    '| Unit | Title | Status | Commit | Before | After | Classic deltas | Record |',
    '|---|---|---|---|---|---|---:|---|',
  ];
  for (const u of units) {
    const r = byUnit[u.id];
    lines.push(`| ${u.id} | ${u.title} | ${r ? r.status : 'not started'} | ${r && r.commit ? `\`${r.commit}\`` : ''} | ${r ? r.before || '' : ''} | ${r ? r.after || '' : ''} | ${r ? r.classic_deltas || '0' : ''} | ${r ? `[${r.file}](records/${r.file})` : ''} |`);
  }
  const unknown = recs.filter((r) => !units.some((u) => u.id === r.unit));
  if (unknown.length || bad.length) {
    lines.push('', '## Records that need fixing', '');
    for (const r of unknown) lines.push(`- ${r.file}: unit ${r.unit} is not in units.json`);
    for (const b of bad) lines.push(`- ${b}`);
  }
  return `${lines.join('\n')}\n`;
}

function main() {
  const o = C.args();
  if (o.help) { console.log(HELP); return; }
  if (o.selftest) {
    const tmp = C.tmpDir('progress');
    fs.writeFileSync(path.join(tmp, 'W3-b.md'), `---\nunit: W3-b\n${o.plant ? '' : 'status: done\n'}commit: abc1234\nbefore: colour=35 font=0 primary=6\nafter: colour=0 font=0 primary=0\nclassic_deltas: 0\n---\n# W3-b\n`);
    fs.writeFileSync(path.join(tmp, 'broken.md'), '# no front matter\n');
    const { recs, bad } = readRecords(tmp);
    C.selftest('progress', [
      ['the good record parses', () => C.assert(recs.length === 1 && recs[0].status === 'done', JSON.stringify(recs))],
      ['a record without front matter is reported, not dropped silently', () => C.assert(bad.some((b) => /broken\.md/.test(b)), JSON.stringify(bad))],
    ]);
    return;
  }
  const { recs, bad } = readRecords(o.records ? path.resolve(o.records) : path.join(DIR, 'records'));
  const md = render(recs, bad);
  if (o.write) { fs.writeFileSync(path.join(DIR, 'PROGRESS.md'), md); console.log('wrote docs/design/themes/PROGRESS.md'); } else process.stdout.write(md);
}

main();
